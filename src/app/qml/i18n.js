var PFX = ["已连接：", "来自 ", "接收完成，已保存到 ", "请在接收文件列表中点按查看：", "已用系统查看器打开："];
var SFX = [" 字节"];

function resolve(tag) {
    if (!tag || tag === "system") return "en";
    if (P[tag]) return tag;
    var s = String(tag).replace(/-/g, "_").toLowerCase();
    if (s.indexOf("zh") === 0) {
        if (s.indexOf("hk") >= 0 || s.indexOf("mo") >= 0) return "zh_HK";
        if (s.indexOf("tw") >= 0 || s.indexOf("hant") >= 0) return "zh_TW";
        return "zh_CN";
    }
    if (s.indexOf("cs") === 0) return "cs";
    return "en";
}

function t(lang, s) {
    if (s === undefined || s === null || s === "") return "";
    var p = P[lang] || P.en;
    var ckey = CN[s];
    var v = (ckey === undefined) ? p[s] : p[ckey];
    if (v !== undefined) return v;
    var i, k;
    for (i = 0; i < PFX.length; ++i) {
        k = PFX[i];
        if (s.indexOf(k) === 0) {
            var m = p["~" + k];
            if (m !== undefined) {
                var rest = s.substring(k.length);
                // "已保存到 文件/路径。": the folder name and the closing full stop are part of the message
                if (k === "接收完成，已保存到 ") {
                    rest = rest.replace(/^文件/, p.files_root || P.en.files_root);
                    rest = rest.replace(/。$/, p.end_stop || P.en.end_stop);
                }
                return m + rest;
            }
        }
    }
    for (i = 0; i < SFX.length; ++i) {
        k = SFX[i];
        if (s.length > k.length && s.substring(s.length - k.length) === k) {
            var m2 = p["@" + k];
            if (m2 !== undefined) return s.substring(0, s.length - k.length) + m2;
        }
    }
    var rn = s.match(/^已选择 ([0-9]+) 个文件$/);
    if (rn) return (p.selected_n || P.en.selected_n).replace("%1", rn[1]);
    var rn2 = s.match(/^已接收 ([0-9]+) 个文件$/);
    if (rn2) return (p.received_n || P.en.received_n).replace("%1", rn2[1]);
    return s;
}

